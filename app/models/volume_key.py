"""Volume DEK model — encrypted-volume key lifecycle (SS-10 CB-03 / CB-01).

A volume DEK is generated by the trusted volume plugin (NOT the control plane),
registered with the control-plane KMS, and wrapped with the master KEK
(envelope encryption). The KEK-wrapped blob is the only key material persisted;
the raw DEK is never stored and never returned to the plugin at registration.

This is a distinct key type from the product DataEncryptionKey / session keys:
it is bound to a volume, addressed by a plugin-held ref (key_id), and
distributed (unwrapped) to a session on attach.
"""
import uuid
from datetime import datetime
from enum import Enum

from sqlalchemy import String, DateTime, Integer, LargeBinary, Index, func
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.dialects.postgresql import UUID

from app.core.database import Base


class VolumeKeyStatus(str, Enum):
    """Volume DEK lifecycle status."""
    ACTIVE = "active"
    REVOKED = "revoked"
    DESTROYED = "destroyed"


class VolumeKey(Base):
    """A volume DEK: plugin-generated, KEK-wrapped at rest, ref-addressed."""
    __tablename__ = "volume_keys"
    __table_args__ = (
        Index("ix_volume_keys_volume_id", "volume_id"),
        Index("ix_volume_keys_status", "status"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    # Plugin-held reference (the "wrapped key ref" / dek_ref that goes into
    # private_data). The Go volume plugin addresses distribute/revoke by this.
    key_id: Mapped[str] = mapped_column(String(255), unique=True, nullable=False, index=True)
    volume_id: Mapped[str] = mapped_column(String(255), nullable=False)
    name: Mapped[str] = mapped_column(String(255), nullable=False, default="")
    algorithm: Mapped[str] = mapped_column(String(32), nullable=False, default="SM4-GCM")
    key_length: Mapped[int] = mapped_column(Integer, nullable=False, default=16)
    # KEK-wrapped DEK blob (envelope encryption). The only persisted key
    # material; the plaintext DEK is never stored. Nulled on revoke (crypto-erase).
    wrapped_key: Mapped[bytes | None] = mapped_column(LargeBinary)
    status: Mapped[str] = mapped_column(String(32), nullable=False, default=VolumeKeyStatus.ACTIVE.value)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
